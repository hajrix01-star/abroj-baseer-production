def verify_inputs():
    records = []
    live = dict(zip(paths, inputs))
    live["sdk/android-35.jar"] = jar
    for relative, expected in hashes.items():
        original = live.get(relative)
        records.append({"path": relative, "expected": hashes[relative],
                        "live": sha(original) if original is not None and original.is_file() else None,
                        "origin": origins[relative],
                        "archived": sha(archived / relative)})
    matched = all(row["expected"] == row["archived"] and
                  (row["origin"].startswith("git:") or row["expected"] == row["live"]) for row in records)
    write_json(output / "source-verification.json", {"all_matched": matched, "inputs": records})
    if not matched:
        raise RuntimeError("Input changed; no frozen-source acceptance")


