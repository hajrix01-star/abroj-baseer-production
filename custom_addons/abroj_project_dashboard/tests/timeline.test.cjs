const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../static/src/dashboard.js'), 'utf8');
const helper = source.slice(source.indexOf('export function timelineLayout'), source.indexOf('\nclass Dashboard')).replace('export function', 'function');
const context = vm.createContext({});
vm.runInContext(helper, context);
const layout = context.timelineLayout([{start:'2026-01-30', end:'2026-02-02'}], new Date(2026, 0, 31), 'ar');
assert.equal(layout.cells.length, 4);
assert.equal(layout.bar({start:'2026-01-31', end:'2026-02-01'}).left, layout.cells[1].left);
assert.equal(layout.bar({start:'2026-01-31', end:'2026-02-01'}).width, layout.cells[3].left - layout.cells[1].left);
assert.equal(layout.today, layout.cells[1].left);
assert.equal(layout.cells[1].week, true);
assert.match(layout.cells[0].label, /يناير/);
assert.match(layout.cells[2].label, /فبراير/);
const long = context.timelineLayout([{start:'2026-01-01', end:'2026-12-31'}], new Date(2026, 5, 1), 'en');
assert.ok(long.step > 1);
assert.ok(long.cells.some(c => !c.label));
assert.match(long.cells[31].label, /Feb/);
assert.ok(long.cells.filter(c => c.label).every(c => c.labelWidth > 0));
assert.equal(context.timelineLayout([], new Date(), 'en'), null);
