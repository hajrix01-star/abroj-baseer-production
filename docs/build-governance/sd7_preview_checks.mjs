import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const path = 'custom_addons/baseer_sales_dashboard/static/src/sales_dashboard.js';
const raw = fs.readFileSync(path, 'utf8');
const source = raw.replace(/^import .*;\r?\n/gm, '').replace(/export (class|function) /g, '$1 ');
const Dashboard = new Function('Component', '_t', source + '\nreturn BaseerSalesDashboard;')(class {}, text => text);
const d = new Dashboard();
const keys = ['sales', 'customers', 'daily_sales', 'daily_customers', 'average_bill'];
d.state = {payload: {has_data: false, cards: Object.fromEntries(keys.map(k => [k, {display:'—',available:false}]))}};
const before = JSON.stringify(d.state.payload);
assert(d.cards.every(card => /^[\d,]+$/.test(card.display)));
assert.equal(JSON.stringify(d.state.payload), before);
d.state.payload.has_data = true;
assert(d.cards.every(card => card.display === '—' && !card.available));
d.state.payload.cards.sales = {display:'0.00',available:true};
assert.equal(d.cards[0].display, '0.00');
d.state.payload.cards.sales = {display:'SERVER 4,447.00',available:true};
assert.equal(d.cards[0].display, 'SERVER 4,447.00');
const result = {status:'pass',source_sha256:crypto.createHash('sha256').update(raw).digest('hex'),checks:['empty payload displays numeric examples','example rendering leaves payload unchanged','recorded but unavailable values remain unavailable','actual zero remains zero','real server-formatted values are preserved']};
fs.writeFileSync('docs/build-governance/sd7-preview-checks.json',JSON.stringify(result,null,2));
console.log('PASS5 preview isolation checks');
