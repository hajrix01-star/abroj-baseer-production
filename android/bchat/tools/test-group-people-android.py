def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def run(*command, timeout=90, check=True):
    result = subprocess.run([str(item) for item in command], text=True, encoding="utf-8",
                            errors="replace", capture_output=True, timeout=timeout)
    with (output / "build.log").open("a", encoding="utf-8") as log:
        # Deliberately exclude signing arguments and any password material.
        log.write(Path(str(command[0])).name + "\n" + result.stdout + result.stderr + "\n")
    if check and result.returncode:
        raise RuntimeError(f"{Path(str(command[0])).name} failed ({result.returncode}); inspect build.log")
    return result


