    /** Remap only the attachment's ASCII modified-UTF path; all v1 class descriptors stay original. */
    private static byte[] replaceSerializedUtf(byte[] source, String oldValue, String newValue) throws Exception {
        byte[] oldBytes = oldValue.getBytes(StandardCharsets.UTF_8), newBytes = newValue.getBytes(StandardCharsets.UTF_8);
        for (int i = 2; i <= source.length - oldBytes.length; i++) {
            if ((source[i - 2] & 255) * 256 + (source[i - 1] & 255) != oldBytes.length) continue;
            boolean matches = true;
            for (int j = 0; j < oldBytes.length; j++) if (source[i + j] != oldBytes[j]) { matches = false; break; }
            if (!matches) continue;
            java.io.ByteArrayOutputStream bytes = new java.io.ByteArrayOutputStream();
            bytes.write(source, 0, i - 2); bytes.write(newBytes.length >>> 8); bytes.write(newBytes.length & 255);
            bytes.write(newBytes); bytes.write(source, i + oldBytes.length, source.length - i - oldBytes.length);
            return bytes.toByteArray();
        }
        throw new AssertionError("Legacy fixture attachment path not found");
    }

