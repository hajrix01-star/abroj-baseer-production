export const translator = (language: Language) => (word: Word) =>
  (language === 'ar' ? ar : en)[word];
export type Translate = ReturnType<typeof translator>;
export function errorWord(error: unknown): Word {
  const code = (error as { code?: string })?.code;
  if (code === 'mfa_required') return 'mfa';
  if (['authentication_failed', 'login_failed', 'invalid_credentials'].includes(code ?? ''))
    return 'credentials';
  if (code === 'offline_expired') return 'expired';
  if (code === 'direct_disabled') return 'directOff';
  if (code === 'media_not_cached') return 'mediaMissing';
  if (code === 'last_admin') return 'lastAdmin';
  if (
    [
      'forbidden',
      'send_denied',
      'room_unavailable',
      'membership_changed',
      'identity_mismatch',
    ].includes(code ?? '')
  )
    return 'forbidden';
  if (
    ['payload_too_large', 'file_too_large', 'attachment_quota', 'invalid_attachment'].includes(
      code ?? '',
    )
  )
    return 'tooLarge';
  return 'error';
}
