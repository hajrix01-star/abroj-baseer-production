const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const pwa = path.join(__dirname, '..', 'static', 'pwa');
const app = fs.readFileSync(path.join(pwa, 'js', 'app.js'), 'utf8');
const i18n = fs.readFileSync(path.join(pwa, 'js', 'i18n.js'), 'utf8');
const screens = fs.readFileSync(path.join(pwa, 'js', 'screens.js'), 'utf8');
const css = fs.readFileSync(path.join(pwa, 'css', 'screens.css'), 'utf8');
const helper = app.match(/function statusBadge\(p\)\{[\s\S]*?\n\}/)[0];
const context = vm.createContext({});
vm.runInContext(`${i18n}\nlet lang = 'ar';
const t = key => translations[key][lang];
const number = n => String(n);
const esc = s => s;
${helper}`, context);
const badge = (status, overdue_days = 0) => context.statusBadge({status, overdue_days});
assert.match(badge('done'), /<svg[^>]*aria-hidden="true"[\s\S]*<path[\s\S]*<\/svg>منجز/);
vm.runInContext("lang = 'en'", context);
assert.match(badge('done'), /<\/svg>Done<\/span>$/);
assert.equal(badge('on_time'), '<span class="phase-status on_time">On time</span>');
assert.equal(badge('overdue', 2), '<span class="phase-status overdue">2 days overdue</span>');
assert.match(css, /\.phase-status\.on_time\{background:rgba\(16,42,92,\.1\);color:var\(--primary\)\}/);
assert.match(css, /\.phase-status\.overdue\{background:#fee2e2;color:#991b1b\}/);
assert.match(css, /\.phase-status\.done\{[^}]*background:#dcfce7;color:#166534\}/);
assert.match(screens, /g\.phases\.map\(p=>[\s\S]*?statusBadge\(p\)/);
assert.match(screens, /p\.phases\.map\(x=>[\s\S]*?statusBadge\(x\)/);
assert.match(app, /async function legacyDetail[\s\S]*?statusBadge\(x\)/);
assert.match(app, /function taskForm[\s\S]*?statusBadge\(phase\)/);
