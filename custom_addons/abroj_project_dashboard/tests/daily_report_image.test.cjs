const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../static/pwa/js/screens.js'), 'utf8');
const helpers = source.slice(source.indexOf('function westernDigits('), source.indexOf('async function shareDailyReport('));
const context = vm.createContext({});
vm.runInContext(helpers, context);
const line = {project_id: 1, project: 'مشروع ١', task: 'النظافة', status: 'late', overdue_days: 3, deadline_old: '2026-01-01', deadline_new: '2026-01-04', deadline_change_days: 3, change_kind: 'postponed'};
assert.equal(context.extensionSentence(line), 'تم تأجيل النظافة من 2026-01-01 إلى 2026-01-04 (3 أيام)');
assert.match(context.extensionSentence({...line, change_kind: 'extended'}), /^تم تمديد/);
assert.match(context.extensionSentence({...line, change_kind: 'advanced'}), /^تم تقديم/);
assert.equal(context.extensionSentence({...line, deadline_old: ''}), '');
const report = context.buildDailyReportModel({engineer: 'موظف', date: '٢٠٢٦-١١-٠١', lines: [line, {...line, task: 'مكتمل', status: 'done', change_kind: ''}, {...line, task: 'مفتوح', status: 'on_time', change_kind: ''}], financial: [{sentence: 'تم استلام مبلغ 15,000 ريال — مشروع ١'}]});
assert.equal(report.date, '2026-11-01');
assert.equal(report.projects[0].sections['متأخر'][0], 'النظافة (3 أيام)');
assert.equal(report.projects[0].sections['منجز'][0], 'مكتمل');
assert.equal(report.projects[0].sections['لم يُنجز'][0], 'مفتوح');
assert.equal(report.financial[0], 'تم استلام مبلغ 15,000 ريال — مشروع 1');
const empty = context.buildDailyReportModel({engineer:'Mustafa Ahmed', projects:[{id:2,name:'Empty',has_activity:false}], lines:[]});
assert.equal(empty.engineer, 'Mustafa Ahmed');
assert.equal(empty.projects[0].hasActivity, false);
const detailed = context.buildDailyReportModel({projects:[{id:1,name:'Project',has_activity:true}], lines:[{...line, progress_from:0,progress_to:0,notes:'  Note  here \nNote here\nTask Created\nتم إنشاء مهمة جديدة'}]});
assert.equal(detailed.projects[0].sections['متأخر'].join('|'), 'النظافة (3 أيام)|Note here');
const changed = context.buildDailyReportModel({lines:[{...line,progress_from:0,progress_to:25}]});
assert.match(changed.projects[0].sections['متأخر'][0], /0% → 25%/);
const wrapped = context.wrapReportText({measureText:s=>({width:Array.from(s).length})}, 'abcdefgh xy z', 3);
assert.ok(Array.from(wrapped).every(s=>s.length<=3));
