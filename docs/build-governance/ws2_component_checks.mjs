import fs from 'node:fs';
import assert from 'node:assert/strict';
const path = 'custom_addons/baseer_work_schedule/static/src/time_field.js';
const source = fs.readFileSync(path, 'utf8').replace(/^import .*;\r?\n/gm, '').replace('export class', 'class');
const registry = { category: () => ({ add() {} }) };
const Field = new Function('Component', 'useState', 'registry', '_t', 'standardFieldProps', source + '\nreturn ScheduleTimeField;')(
    class {}, value => value, registry, value => value, {});
const checks = [];
const check = (name, fn) => { fn(); checks.push({name, passed:true}); };
let resolve, reject;
let calls = [];
const record = {data:{time_to:'16:00'}, update: values => {calls.push(values); return new Promise((r,j)=>{resolve=r;reject=j;});}};
const field = new Field();
field.props = {record, name:'time_to', allowEndOfDay:true};
field.setup();
const controls = {hour:'21',minute:'07'};
const event = {currentTarget:{parentElement:{querySelector: key => ({value: key.includes('hour') ? controls.hour : controls.minute})}}};
check('24 end-hour choices and all60minutes',()=>{assert.equal(field.hours.length,25);assert.equal(field.minutes.length,60);});
const pending = field.onChange(event);
check('rawHHMM sent, busy immediately',()=>{assert.deepEqual(calls,[{time_to:'21:07'}]);assert.equal(field.state.busy,true);});
controls.hour='22';
await field.onChange(event);
check('overlap ignored before DOM disable and onchange response',()=>assert.equal(calls.length,1));
record.data.time_to='21:07';resolve();await pending;
check('unlock after reply',()=>assert.equal(field.state.busy,false));
controls.hour='24';controls.minute='59';
const end = field.onChange(event);
check('24 endpoint sends00minutes',()=>assert.deepEqual(calls[1],{time_to:'24:00'}));
record.data.time_to='24:00';resolve();await end;
check('endpoint minute only00',()=>assert.deepEqual(field.minutes,['00']));
controls.hour='03';controls.minute='00';
const failure = field.onChange(event);reject(new Error('native onchange error'));
await assert.rejects(failure,/native onchange error/);
check('unlock after rejected onchange',()=>assert.equal(field.state.busy,false));
field.props.allowEndOfDay=false;
check('start excludes24',()=>{assert.equal(field.hours.length,24);assert(!field.hours.includes('24'));});
check('literal western padded choices',()=>assert.deepEqual(field.hours.slice(0,3),['00','01','02']));
let stopped=false;
const key={key:'Tab',shiftKey:false,target:{dataset:{part:'hour'}},currentTarget:{querySelector:()=>({disabled:false})},stopPropagation(){stopped=true;}};
field.onKeydown(key);
check('Tab stays within hour/minute field',()=>assert.equal(stopped,true));
stopped=false;key.target.dataset.part='minute';field.onKeydown(key);
check('last control Tab keeps native nextfield navigation',()=>assert.equal(stopped,false));
key.shiftKey=true;field.onKeydown(key);
check('ShiftTab returns from minute to hour',()=>assert.equal(stopped,true));
fs.writeFileSync('docs/build-governance/ws2-component-checks.json',JSON.stringify({status:'passed',checks,
  scope:'Actual component source with stubbed Owl/registry and deferred native record.update; complements actual UI tests, not full browser lifecycle simulation.'},null,2));
console.log(`${checks.length} component checks passed`);
