    private static void expect(Class<? extends Throwable> expected, Test action) throws Exception {
        try { action.run(); }
        catch (Throwable actual) {
            if (expected.isInstance(actual)) return;
            throw new AssertionError("Expected " + expected.getSimpleName() + ", got " + actual, actual);
        }
        throw new AssertionError("Expected " + expected.getSimpleName() + " but action succeeded");
    }
