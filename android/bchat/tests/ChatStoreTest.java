    private static void attachmentReferences() throws Exception {
        try (Fixture f = new Fixture()) {
            ChatStore.Attachment draft = f.attachment("draft.txt"), pending = f.attachment("pending.txt");
            f.store.setDraft(A, A_OPS, "Draft", Arrays.asList(draft));
            ChatStore.PendingShare share = f.store.stagePendingShare("Share", Arrays.asList(pending));
            equal(new HashSet<String>(Arrays.asList(draft.path, pending.path)), f.store.attachmentPaths());
            expect(UnsupportedOperationException.class, () -> f.store.attachmentPaths().clear());
            f.store.cancelPendingShare(share.id);
            equal(Collections.singleton(draft.path), f.store.attachmentPaths());
            f.store.send(A, A_OPS);
            equal(Collections.singleton(draft.path), f.store.attachmentPaths());
            f.reopen();
            equal(Collections.singleton(draft.path), f.store.attachmentPaths());
        }
    }

    private static void syntheticSeeds() throws Exception {
        try (Fixture f = new Fixture()) {
            equal(3, f.store.companies().size());
            equal(A, f.store.companies().get(0).id);
            equal(260, f.store.messageCount(A, A_OPS));
            Set<String> ids = new HashSet<String>();
            for (ChatStore.Company company : f.store.companies()) {
                check(company.name.contains("التجريبية"), "Company label must state synthetic");
                equal(5, f.store.conversations(company.id).size());
                for (ChatStore.Conversation conversation : f.store.conversations(company.id)) {
                    check(ids.add(conversation.id), "Conversation ids must be globally unique");
                    equal(company.id, conversation.companyId);
                    equal(ChatStore.DEMO_HISTORY, f.store.lastMessage(company.id, conversation.id).status);
                }
            }
        }
    }

    private static void isolatedDrafts() throws Exception {
        try (Fixture f = new Fixture()) {
            ChatStore.Attachment a = f.attachment("nour.txt"), b = f.attachment("madar.txt");
            f.store.setDraft(A, A_OPS, "Nour operations", Arrays.asList(a));
            f.store.setDraft(A, A_SARA, "Nour Sara", NONE);
            f.store.setDraft(B, B_OPS, "Madar operations", Arrays.asList(b));
            equal("Nour operations", f.store.draft(A, A_OPS).text);
            equal(a.id, f.store.draft(A, A_OPS).attachments.get(0).id);
            equal("Nour Sara", f.store.draft(A, A_SARA).text);
            equal("Madar operations", f.store.draft(B, B_OPS).text);
            equal(b.id, f.store.draft(B, B_OPS).attachments.get(0).id);
            equal("", f.store.draft(C, C + "-ops").text);
            f.store.setDraft(A, A_OPS, "", NONE);
            equal("Nour Sara", f.store.draft(A, A_SARA).text);
            equal("Madar operations", f.store.draft(B, B_OPS).text);
        }
    }

